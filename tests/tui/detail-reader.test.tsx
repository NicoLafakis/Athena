import { describe, expect, it, vi } from 'vitest'
import { render } from 'ink-testing-library'
import { DetailReader } from '../../src/tui/components/DetailReader.js'

const tick = () => new Promise(resolve => setTimeout(resolve, 20))
describe('local detail reader', () => {
  it('shows export failure and leaves the retained content readable', async () => {
    const exportText = vi.fn(async () => { throw new Error('disk unavailable') })
    const { stdin, lastFrame, unmount } = render(<DetailReader title="Tool result" text="retained content" rows={12} columns={80} onClose={vi.fn()} onExport={exportText} />)
    await tick()
    stdin.write('e')
    await tick()
    expect(lastFrame()).toContain('Export failed: Error: disk unavailable')
    expect(lastFrame()).toContain('retained content')
    expect(lastFrame()).not.toContain('Saved:')
    unmount()
  })
  it('finds a late result, exports all retained text, and closes without submitting work', async () => {
    const close = vi.fn()
    const exportText = vi.fn(async () => 'saved.txt')
    const text = Array.from({ length: 200 }, (_, i) => `result-${i}`).join('\n')
    const { stdin, lastFrame, unmount } = render(<DetailReader title="Tool result" text={text} rows={12} columns={40} onClose={close} onExport={exportText} />)
    await tick()
    stdin.write('/')
    await tick()
    stdin.write('result-199')
    await tick()
    stdin.write('\r')
    await tick()
    expect(lastFrame()).toContain('result-199')
    stdin.write('e')
    await tick()
    expect(exportText).toHaveBeenCalledWith(text)
    expect(lastFrame()).toContain('saved.txt')
    stdin.write('\u001b')
    await tick()
    expect(close).toHaveBeenCalledOnce()
    unmount()
  })
})


describe('permission reader input ownership', () => {
  it('does not grant after resizing the grant reader below its readable size', async () => {
    const grant = vi.fn()
    const close = vi.fn()
    const { stdin, rerender, lastFrame, unmount } = render(<DetailReader title="Grant" text="scope" rows={12} columns={40} onClose={close} onGrant={grant} />)
    await tick()
    rerender(<DetailReader title="Grant" text="scope" rows={3} columns={18} onClose={close} onGrant={grant} />)
    await tick()
    expect(lastFrame()).toContain('Resize')
    stdin.write('a')
    await tick()
    expect(grant).not.toHaveBeenCalled()
    stdin.write('\u001b')
    await tick()
    expect(close).toHaveBeenCalledOnce()
    unmount()
  })
  it('keeps n as search-next in permission details; x is the visible deny control', async () => {
    const deny = vi.fn()
    const text = ['match-first', ...Array.from({ length: 25 }, () => 'filler'), 'match-last'].join('\n')
    const { stdin, lastFrame, unmount } = render(<DetailReader title="Permission" text={text} rows={12} columns={40} onClose={vi.fn()} onDeny={deny} />)
    await tick()
    stdin.write('/')
    await tick()
    stdin.write('match')
    await tick()
    stdin.write('\r')
    await tick()
    stdin.write('n')
    await tick()
    expect(deny).not.toHaveBeenCalled()
    expect(lastFrame()).toContain('match-last')
    expect(lastFrame()).toContain('x deny')
    stdin.write('x')
    await tick()
    expect(deny).toHaveBeenCalledOnce()
    unmount()
  })
})
